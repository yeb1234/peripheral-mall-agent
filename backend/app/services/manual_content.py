def sections(kind: str, item: dict) -> list[dict]:
    """按来源类型返回章节切片。driver 是二进制不切片，返回空。"""
    if kind == "manual":
        return manual_sections(item)
    if kind == "resource":
        return resource_sections(item)
    return []


def render_document(kind: str, item: dict) -> str:
    """完整正文：下载文件与知识库切片共用这一份内容。"""
    if kind == "driver":
        return ""  # 由 resource_service 的占位文本处理
    head = (
        f"P4 PERIPHERAL · {CATEGORY_CN.get(item.get('category', ''), '外设')} 官方文档\n"
        f"{'=' * 56}\n"
        f"型号：{item.get('product_sku', '')}　名称：{item.get('product_name', '')}\n"
        f"文档：{item.get('title', '')}\n"
        f"版本：v{item.get('version', '1.0')}　语言：{item.get('lang', 'zh')}　"
        f"发布：{item.get('release_date', '—')}\n"
        f"{'-' * 56}\n"
    )
    body = []
    for s in sections(kind, item):
        body.append(f"\n第 {s['section_no']} 节　{s['section_title']}\n{s['content']}\n")
    foot = (
        f"\n{'-' * 56}\n"
        "本文档为演示用结构化说明书，由商品资料自动生成并与客服知识库同源同步。\n"
        f"校验：下载后可用资源下载页给出的 SHA256 校验文件完整性。\n"
    )
    return head + "".join(body) + foot
