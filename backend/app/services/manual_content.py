def _fmt(template: str, item: dict) -> str:
    """模板里的 {product_name} / {pd} 等占位按商品信息补齐。"""
    vals = {
        "product_name": item.get("product_name") or item.get("title") or "P4 外设",
        "sku": item.get("product_sku", ""),
        "pd": "100",
    }
    try:
        return template.format(**vals)
    except (KeyError, IndexError):
        return template


